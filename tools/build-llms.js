#!/usr/bin/env node
// Builds llms.txt and llms-full.txt from tools/llms-intro.md, memory-map.json
// and the engine lists in engine.js, so the files a language model reads can
// never drift from the chip.
//
//   node tools/build-llms.js          write both files
//   node tools/build-llms.js --check  exit 1 if either is out of date (CI)
//
// llms.txt is short: the intro, the engines, one line per pack.
// llms-full.txt adds every field with its address, type, range and note.
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const read = f => fs.readFileSync(path.join(root, f), 'utf8');
const map = JSON.parse(read('memory-map.json'));
const hex = n => '$' + n.toString(16).toUpperCase().padStart(4, '0');
const size = f => (f.type === 'u16' ? 2 : f.type === 'steps' ? 16 : (f.type === 'readonly' || f.type === 'table') ? (f.size || 1) : 1);

// The engine list for each voice, in the order engine.js builds it:
// the SYNTH_IDS literal, then each SYNTH_IDS.voice.push('name') line
function engineLists() {
  const src = read('engine.js');
  const lit = src.match(/const SYNTH_IDS = \{([\s\S]*?)\};/);
  if (!lit) throw new Error('SYNTH_IDS not found in engine.js');
  const lists = {};
  for (const m of lit[1].matchAll(/(\w+):\s*\[([^\]]*)\]/g)) lists[m[1]] = [...m[2].matchAll(/'([^']+)'/g)].map(x => x[1]);
  for (const m of src.matchAll(/^SYNTH_IDS\.(\w+)\.push\('([^']+)'\)/gm)) lists[m[1]].push(m[2]);
  return lists;
}

function engines() {
  const lists = engineLists();
  const lines = [];
  for (const r of map.regions) {
    if (!r.fields) continue;
    let a = parseInt(r.start, 16);
    for (const f of r.fields) {
      if (f.type === 'engine') lines.push(`- ${f.name} (${hex(a)}): ${lists[f.voice].map((n, i) => `${i} ${n}`).join(', ')}`);
      a += size(f);
    }
  }
  return lines.join('\n');
}

const firstSentence = s => { const m = String(s || '').match(/^.*?[.:](\s|$)/); return (m ? m[0] : String(s || '')).trim().replace(/[.:]$/, ''); };

function packs(full) {
  const out = [full ? '## Every field' : '## Packs', ''];
  out.push(full
    ? 'Grouped by pack, in CAPS bit order. Each line: name, address, type, range or options, note.'
    : 'In CAPS bit order: bit, name, addresses, what it is, its fields. llms-full.txt has every field with its range and note.');
  out.push('');
  const bits = Object.entries(map.caps_bits).sort((a, b) => Number(a[0]) - Number(b[0]));
  for (const [bit, pack] of bits) {
    const regions = map.regions.filter(r => r.pack === pack);
    const defined = regions.filter(r => r.fields);
    const span = regions.length ? `${hex(parseInt(regions[0].start, 16))}-${hex(parseInt(regions[regions.length - 1].end, 16))}` : '';
    if (!defined.length) {
      if (!full) out.push(`- bit ${bit} ${pack} (${span}): planned, no bytes yet`);
      continue;
    }
    const fields = [];
    for (const r of defined) {
      let a = parseInt(r.start, 16);
      for (const f of r.fields) {
        if (!full) fields.push(f.name);
        else {
          const n = size(f);
          const where = n > 1 ? `${hex(a)}-${hex(a + n - 1)}` : hex(a);
          let range = '';
          if (f.options) range = ' [' + f.options.map((o, i) => `${i} ${o}`).join(', ') + ']';
          else if (f.bits) range = ' bits [' + f.bits.map((o, i) => `${i} ${o}`).join(', ') + ']';
          else if ('min' in f) range = ` ${f.min}-${f.max}`;
          else if (f.type === 'engine') range = ' see Engines';
          const note = f.note || (r.fields.length === 1 ? firstSentence(r.about) : '');
          fields.push(`  - ${f.name} ${where} ${f.type}${range}${note ? ': ' + note : ''}`);
        }
        a += size(f);
      }
    }
    const about = (map.pack_about || {})[pack];
    if (!about) throw new Error(`memory-map.json pack_about has no line for ${pack}`);
    if (full) {
      out.push(`### ${pack} (bit ${bit}, ${span})`, '', about + '.', '', ...fields, '');
    } else {
      out.push(`- bit ${bit} ${pack} (${span}): ${about}. Fields: ${fields.join(', ')}`);
    }
  }
  return out.join('\n').trimEnd() + '\n';
}

const files = `## Files

- [memory-map.json](memory-map.json): the contract, every region and field
- [llms-full.txt](llms-full.txt): this file plus every field
- [README.md](README.md): the long explanation, for people
- [tools/render.js](tools/render.js): run lines, render, measure
- [sounds.js](sounds.js): sounds as text, by field name
`;

function build() {
  const intro = read('tools/llms-intro.md').replace('{{ENGINES}}', engines()).trimEnd() + '\n';
  const stamp = `\n<!-- Generated by tools/build-llms.js from tools/llms-intro.md, memory-map.json and engine.js. Do not edit. -->\n`;
  return {
    'llms.txt': intro + '\n' + packs(false) + '\n' + files + stamp,
    'llms-full.txt': intro + '\n' + packs(false) + '\n' + packs(true) + '\n' + files + stamp
  };
}

function main() {
const out = build();
if (process.argv.includes('--check')) {
  const stale = Object.entries(out).filter(([f, text]) => !fs.existsSync(path.join(root, f)) || read(f) !== text).map(([f]) => f);
  if (stale.length) { console.error(`${stale.join(', ')} out of date: run node tools/build-llms.js`); process.exit(1); }
  console.log('llms ok: llms.txt and llms-full.txt match the map');
} else {
  for (const [f, text] of Object.entries(out)) fs.writeFileSync(path.join(root, f), text);
  console.log(`wrote llms.txt (${out['llms.txt'].length} bytes) and llms-full.txt (${out['llms-full.txt'].length} bytes)`);
}
}

if (require.main === module) main();
module.exports = { engineLists, build };
